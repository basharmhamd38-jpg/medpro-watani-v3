// اهتزازات خفيفة بمعايير التطبيقات العالمية — عبر Vibration المدمجة (بلا اعتماديات إضافية)
// أنماط مدروسة: قصيرة وخفيفة، لا تزعج ولا تُهنج
import { Vibration } from 'react-native';

function buzz(pattern: number | number[]): void {
  // الاهتزاز يُؤجَّل لما بعد معالجة اللمسة (setTimeout 0):
  // حتى لو علّق موتور الاهتزاز في جهاز معين، لا يحجب استجابة
  // الواجهة أبدًا — تحديث الحالة والرسم يحدثان أولًا دائمًا.
  // (درس v10: الاهتزاز كان السبب الجذري لتجميد اختيار الإجابات)
  setTimeout(() => {
    try {
      // فحص دفاعي: Vibration قد تكون غير متوفرة في بعض البيئات
      if (!Vibration || typeof Vibration.vibrate !== 'function') return;
      Vibration.vibrate(pattern);
    } catch {
      // أجهزة بلا موتور اهتزاز — تجاهل بصمت
    }
  }, 0);
}

export const haptics = {
  /** لمسة خفيفة: اختيار خيار، تبديل، ضغط زر */
  tap: () => buzz(8),
  /** إجابة: صح = نبضة واحدة خفيفة • خطأ = نبضتين خفيفتين */
  answer: (correct: boolean) =>
    correct ? buzz(15) : buzz([0, 30, 40, 30]),
  /** إتمام وحدة/اختبار بنجاح: تتابع احتفالي خفيف */
  complete: () => buzz([0, 25, 60, 25, 60, 60]),
  /** تنبيه/تحذير خفيف */
  warn: () => buzz(25),
};
